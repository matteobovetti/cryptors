// Interoperability with cryptors::hpke: Go's crypto/hpke opens messages that
// cryptors sealed, in every suite both support, so that the throughput
// comparison is between two implementations of the same thing, and a broken
// build fails the run instead of passing as a throughput figure. The other
// direction, cryptors opening what Go sealed, is the Rust test
// `opens_what_go_sealed` in src/hpke/tests.rs.
//
// The messages are the ones of the Rust test `seals_what_go_opens`, which keeps
// them in step with the code: Base mode to the recipient
// DeriveKeyPair(stream("interop ikmR", kem_id, Nsk)) of each KEM, info
// "cryptors interop", three messages through one context, an export of 48
// bytes for "interop export", and a single-shot enc || ct of "single shot" with
// no associated data.
package hpkecmp

import (
	"bytes"
	"crypto/ecdh"
	"crypto/hpke"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"testing"
)

// stream returns n bytes: SHA-256(label || be32(i) || be32(j)) for j = 0, 1,
// ..., as in the Rust tests.
func stream(label string, i uint32, n int) []byte {
	var out []byte
	for j := uint32(0); len(out) < n; j++ {
		h := sha256.New()
		h.Write([]byte(label))
		binary.Write(h, binary.BigEndian, i)
		binary.Write(h, binary.BigEndian, j)
		out = h.Sum(out)
	}
	return out[:n]
}

