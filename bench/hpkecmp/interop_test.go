func TestOpensCryptorsOutput(t *testing.T) {
	info := []byte("cryptors interop")
	messages := []struct{ aad, pt []byte }{
		{nil, nil},
		{[]byte("aad 1"), stream("interop pt", 1, 100)},
		{nil, stream("interop pt", 2, 17)},
	}
	for _, v := range sealedByCryptors {
		k := kems[v.kem]
		skR, err := hpke.DHKEM(k.curve).DeriveKeyPair(stream("interop ikmR", uint32(v.kem), k.nsk))
		if err != nil {
			t.Fatal(err)
		}
		kdf, err := hpke.NewKDF(v.kdf)
		if err != nil {
			t.Fatal(err)
		}
		aead, err := hpke.NewAEAD(v.aead)
		if err != nil {
			t.Fatal(err)
		}
		recipient, err := hpke.NewRecipient(mustHex(t, v.enc), skR, kdf, aead, info)
		if err != nil {
			t.Fatalf("KEM %04x, KDF %04x, AEAD %04x: %v", v.kem, v.kdf, v.aead, err)
		}
		if v.aead != 0xffff {
			for i, m := range messages {
				pt, err := recipient.Open(m.aad, mustHex(t, v.ciphertexts[i]))
				if err != nil {
					t.Fatalf("KEM %04x, KDF %04x, AEAD %04x, message %d: %v", v.kem, v.kdf, v.aead, i, err)
				}
				if !bytes.Equal(pt, m.pt) {
					t.Errorf("KEM %04x, KDF %04x, AEAD %04x, message %d: got %x", v.kem, v.kdf, v.aead, i, pt)
				}
			}
			pt, err := hpke.Open(skR, kdf, aead, info, mustHex(t, v.singleShot))
			if err != nil || string(pt) != "single shot" {
				t.Errorf("KEM %04x, KDF %04x, AEAD %04x, single shot: %q, %v", v.kem, v.kdf, v.aead, pt, err)
			}
		}
		export, err := recipient.Export("interop export", 48)
		if err != nil {
			t.Fatal(err)
		}
		if hex.EncodeToString(export) != v.export {
			t.Errorf("KEM %04x, KDF %04x, AEAD %04x: export %x", v.kem, v.kdf, v.aead, export)
		}
	}
}
